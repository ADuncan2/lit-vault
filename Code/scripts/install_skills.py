"""
install_skills.py — generate the personalised global lit-vault skills.

Run by the lit-vault-setup skill at its consent step, never silently. Reads
the in-repo skills in .claude/skills/ and writes personalised copies to
~/.claude/skills/{lit-vault-search,lit-vault-refresh}/SKILL.md, so any
Claude session on this machine can query this vault.

Stamping replaces the frontmatter (adding `metadata.generated-by`) and the
marked blocks in the body:

  <!-- stamp:about -->   who the vault belongs to, where it is, how to uninstall
  <!-- stamp:routes -->  only the routes to the vault that exist for this user

An existing install is regenerated in place if it carries our
`generated-by`; a same-named skill without it is left alone unless --force.
Uninstall = delete the two folders (the stamped files say so too).

Stdlib only.

Usage:
    python Code/scripts/install_skills.py --user-name "Sam" [--linked-computer]
        [--repo OWNER/NAME] [--dest ~/.claude/skills] [--dry-run] [--force]
"""

import argparse
import datetime
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKILLS_SRC = ROOT / ".claude" / "skills"
SKILLS = ["lit-vault-search", "lit-vault-refresh"]
FM_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)
MARKER = "generated-by: lit-vault setup"


def version() -> str:
    with open(ROOT / "Code" / "pyproject.toml", "rb") as f:
        return tomllib.load(f)["project"]["version"]


def frontmatter_field(fm: str, key: str) -> str:
    m = re.search(rf"^{key}:\s*(.*)$", fm, re.M)
    return m.group(1).strip() if m else ""


def routes_block(vault: Path, linked: bool, repo: str | None) -> str:
    routes = [
        f"**The local folder** `{vault}` — Claude Code run there, or the folder "
        "connected to the session.",
    ]
    if linked:
        routes.append(
            "**The linked computer.** If a shell on that computer is available, "
            f"run the searches there, in `{vault}`. Otherwise list the folder "
            "to find the vault, then stage only what each stage needs "
            "(`papers.json` first, then individual notes). Never stage the "
            "whole vault.")
    if repo:
        routes.append(
            f"**GitHub.** Add `{repo}` (private) to the session and shallow-"
            "clone it. Report the date of the latest commit, because the clone "
            "can lag the local copy. `Fulltext/` is usually gitignored; if it "
            "is absent, say that stage 3 is unavailable on this route.")
    need = ["run the session in the vault folder or connect it"]
    if linked:
        need.append("link the computer")
    if repo:
        need.append(f"allow access to `{repo}`")
    routes.append("**None of these** — stop and say what is needed: "
                  + ", ".join(need) + ".")
    return "\n".join(f"{i}. {r}" for i, r in enumerate(routes, 1))


def about_block(name: str, user: str, vault: Path, dest: Path, ver: str) -> str:
    today = datetime.date.today().isoformat()
    return (f"Generated for {user} by lit-vault setup v{ver} on {today}. "
            f"Here \"the user\" is {user}, and the vault is `{vault}` — "
            f"the commands below run from that folder.\n"
            f"Do not edit this file: re-run the lit-vault-setup skill in the "
            f"vault to regenerate it. To uninstall, delete the folder "
            f"`{dest / name}`.")


def replace_block(text: str, tag: str, body: str) -> str:
    pat = re.compile(rf"(<!-- stamp:{tag} -->\n).*?(\n<!-- /stamp:{tag} -->)", re.S)
    if not pat.search(text):
        return text
    return pat.sub(lambda m: m.group(1) + body + m.group(2), text)


def stamp(src: str, name: str, user: str, vault: Path, dest: Path, ver: str,
          linked: bool, repo: str | None) -> str:
    m = FM_RE.match(src)
    if not m:
        raise SystemExit(f"error: {name}: no frontmatter in the in-repo skill")
    desc = frontmatter_field(m.group(1), "description").strip('"')
    desc = desc.replace("the user's", f"{user}'s")
    fm = (f"---\nname: {name}\ndescription: \"{desc} Vault: {vault.as_posix()}\"\n"
          f"metadata:\n  {MARKER} v{ver}\n---\n")
    body = src[m.end():]
    body = replace_block(body, "about", about_block(name, user, vault, dest, ver))
    body = replace_block(body, "routes", routes_block(vault, linked, repo))
    return fm + body


def main() -> int:
    ap = argparse.ArgumentParser(description="Install the personalised global lit-vault skills.")
    ap.add_argument("--user-name", required=True, help="how the skills refer to you")
    ap.add_argument("--linked-computer", action="store_true",
                    help="claude.ai / desktop-app sessions can reach this computer")
    ap.add_argument("--repo", metavar="OWNER/NAME",
                    help="private GitHub repo holding this vault, if any")
    ap.add_argument("--dest", type=Path, default=Path.home() / ".claude" / "skills")
    ap.add_argument("--force", action="store_true",
                    help="overwrite a same-named skill that lit-vault did not generate")
    ap.add_argument("--dry-run", action="store_true", help="print, write nothing")
    args = ap.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    ver = version()
    vault = ROOT.resolve()
    outputs = {}
    for name in SKILLS:
        src = (SKILLS_SRC / name / "SKILL.md").read_text(encoding="utf-8")
        target = args.dest / name / "SKILL.md"
        if target.exists() and MARKER not in target.read_text(encoding="utf-8") \
                and not args.force:
            print(f"error: {target} exists and was not generated by lit-vault "
                  "setup; move it aside or pass --force", file=sys.stderr)
            return 1
        outputs[target] = stamp(src, name, args.user_name, vault, args.dest, ver,
                                args.linked_computer, args.repo)

    for target, text in outputs.items():
        if args.dry_run:
            print(f"--- {target}\n{text}")
            continue
        existed = target.exists()
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"{'regenerated' if existed else 'installed'}: {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
